/* /repos/:repoId/onboarding — the Onboarding Tour (SPEC-02).
   GET is read-only (nothing generates on open); the tour is only generated / regenerated by an
   explicit click. Mutually exclusive states (loading / error / empty / generating / data) are
   early returns. While generating, no Generate/Regenerate button is rendered (AC-33). */
"use client";

import React from "react";
import { useParams } from "next/navigation";
import { useTranslations } from "next-intl";
import { EmptyState, ErrorState, Icon, Skeleton } from "@devdigest/ui";
import { AppShell } from "@/components/app-shell";
import { RepoNotFound } from "@/components/repo-not-found";
import { useGenerateOnboardingTour, useOnboardingTour } from "@/lib/hooks/onboarding-tour";
import { useRepoNotFound } from "@/lib/repo-context";
import { SKELETON_CARDS } from "./constants";
import { isStale, tourHref } from "./helpers";
import { useActiveSection } from "./hooks/useActiveSection";
import { s } from "./styles";
import { ArchitectureSection } from "./_components/ArchitectureSection";
import { CriticalPathsSection } from "./_components/CriticalPathsSection";
import { FirstTasksSection } from "./_components/FirstTasksSection";
import { ReadingPathSection } from "./_components/ReadingPathSection";
import { RunLocallySection } from "./_components/RunLocallySection";
import { SectionNav } from "./_components/SectionNav";
import { StaleNote } from "./_components/StaleNote";
import { TourFooter } from "./_components/TourFooter";
import { TourHeader } from "./_components/TourHeader";

function TourShell({ crumbLabel, children }: { crumbLabel: string; children: React.ReactNode }) {
  const t = useTranslations("onboarding");
  return (
    <AppShell crumb={[{ label: crumbLabel }, { label: t("title") }]}>
      <div style={s.page}>{children}</div>
    </AppShell>
  );
}

export function OnboardingTourView() {
  const t = useTranslations("onboarding");
  const { repoId } = useParams<{ repoId: string }>();
  const repoNotFound = useRepoNotFound(repoId);

  const { data, isLoading, isError, refetch } = useOnboardingTour(repoId);
  const generate = useGenerateOnboardingTour(repoId);

  const tour = data?.tour ?? null;
  const provenance = data?.provenance ?? null;
  const showTour = tour !== null && provenance !== null;
  const generating = generate.isPending || data?.status === "generating";
  const { active, select } = useActiveSection(showTour);

  const crumbLabel = data?.repo.full_name ?? t("crumbRepo");
  const onGenerate = () => generate.mutate();
  const generateError = generate.isError ? (
    <div style={s.error} role="alert">
      {t("generateError", { message: generate.error instanceof Error ? generate.error.message : "" })}
    </div>
  ) : null;

  if (repoNotFound) {
    return (
      <AppShell crumb={[{ label: crumbLabel }, { label: t("title") }]}>
        <RepoNotFound />
      </AppShell>
    );
  }

  if (isLoading) {
    return (
      <TourShell crumbLabel={crumbLabel}>
        <div style={s.skeletons} aria-busy="true">
          {Array.from({ length: SKELETON_CARDS }, (_, i) => (
            <Skeleton key={i} height={180} />
          ))}
        </div>
      </TourShell>
    );
  }

  if (isError || !data) {
    return (
      <TourShell crumbLabel={crumbLabel}>
        <ErrorState title={t("loadError.title")} onRetry={() => refetch()} />
      </TourShell>
    );
  }

  if (data.status === "none" && !generating) {
    return (
      <TourShell crumbLabel={crumbLabel}>
        {generateError}
        <EmptyState
          icon="Layers"
          title={t("generate.title")}
          body={t("generate.body")}
          cta={t("generate.cta")}
          onCta={onGenerate}
        />
      </TourShell>
    );
  }

  const fullName = data.repo.full_name;
  const sha = provenance?.indexed_sha;
  const transformHref = tourHref(tour?.link_paths ?? [], fullName, sha);

  return (
    <TourShell crumbLabel={crumbLabel}>
      <div style={s.layout}>
        {showTour && <SectionNav active={active} onSelect={select} />}
        <div style={s.main}>
          <TourHeader
            repoName={fullName}
            provenance={provenance}
            basis={tour?.basis ?? null}
            lastFailure={data.last_failure}
            generating={generating}
            onRegenerate={onGenerate}
          />
          {generating && (
            <div style={s.banner} role="status">
              <Icon.RefreshCw size={14} style={{ animation: "ddspin 1s linear infinite" }} />
              <div>
                <div>{t("generating")}</div>
                <div style={{ color: "var(--text-muted)" }}>{t("generatingHint")}</div>
              </div>
            </div>
          )}
          {generateError}
          {showTour && isStale(data.current_index_sha, provenance.indexed_sha) && data.current_index_sha && (
            <StaleNote generatedSha={provenance.indexed_sha} currentSha={data.current_index_sha} />
          )}
          {showTour && (
            <div style={s.sections}>
              <ArchitectureSection section={tour.architecture} transformHref={transformHref} />
              <CriticalPathsSection section={tour.critical_paths} fullName={fullName} sha={sha} />
              <RunLocallySection section={tour.run_locally} />
              <ReadingPathSection section={tour.reading_path} fullName={fullName} sha={sha} />
              <FirstTasksSection
                section={tour.first_tasks}
                fullName={fullName}
                sha={sha}
                transformHref={transformHref}
              />
            </div>
          )}
          {showTour && <TourFooter provenance={provenance} />}
        </div>
      </div>
    </TourShell>
  );
}
