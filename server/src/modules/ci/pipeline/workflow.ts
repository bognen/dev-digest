import { parseDocument } from 'yaml';
import {
  CI_WORKFLOW_VERSION,
  CiSlug,
  ciAgentDir,
  ciCheckName,
} from '@devdigest/shared';
import type { CiPostAs, CiTrigger } from '@devdigest/shared';
import {
  ACTION_PINS,
  CI_MAX_DIFF_BYTES,
  CI_MAX_DIFF_LINES,
  NODE_VERSION,
} from '../constants.js';
import { pullRequestsPermission } from '../helpers.js';

/**
 * Workflow generator + linter (pure). Security posture (NFR-1):
 *  - `pull_request` only (never `pull_request_target`);
 *  - explicit least-privilege `permissions`;
 *  - every executed action pinned to a full commit SHA;
 *  - checkout at the PR *base* SHA with `persist-credentials: false`, so PR-controlled
 *    code never runs with secrets;
 *  - no `${{ }}` expression inside `run:`; PR-derived values go through `env:`;
 *  - fork / Dependabot PRs are skipped by the runner itself (secrets unavailable).
 */

const TRIGGER_ORDER: readonly CiTrigger[] = ['opened', 'synchronize', 'reopened'];

export interface GenerateWorkflowInput {
  slug: string;
  triggers: readonly CiTrigger[];
  postAs: CiPostAs;
  version?: number;
}

const pin = (p: { repo: string; sha: string; tagComment: string }): string =>
  `${p.repo}@${p.sha} # ${p.tagComment}`;

export function generateWorkflow(input: GenerateWorkflowInput): string {
  const slug = CiSlug.parse(input.slug);
  const version = input.version ?? CI_WORKFLOW_VERSION;
  const types = TRIGGER_ORDER.filter((t) => input.triggers.includes(t));
  if (types.length === 0) throw new Error('generateWorkflow: at least one trigger is required');
  const prPerm = pullRequestsPermission(input.postAs);
  const runner = `${ciAgentDir(slug)}runner/index.js`;

  return `# DevDigest review agent "${slug}" - generated by DevDigest (workflow version ${version}).
# You may edit this file; re-exporting from DevDigest offers to regenerate it.
#
# Security notes:
#  - Runs on pull_request only (never pull_request_target) with least-privilege permissions.
#  - Checks out the PR BASE commit and never executes code from the PR head.
#  - Fork and Dependabot pull requests have no access to secrets: the runner skips the
#    review there and prints a notice in the job summary (the check passes, PR unreviewed).
#  - The install PR itself is skipped the same way: its base commit has no runner yet.
#  - Replace the runner step with the commented action once it is published:
#      # uses: devdigest/review-action@v1
name: DevDigest review (${slug})

on:
  pull_request:
    types: [${types.join(', ')}]

permissions:
  contents: read
  pull-requests: ${prPerm}

concurrency:
  group: devdigest-review-${slug}-\${{ github.event.pull_request.number }}
  cancel-in-progress: true

env:
  DEVDIGEST_MAX_DIFF_BYTES: "${CI_MAX_DIFF_BYTES}"
  DEVDIGEST_MAX_DIFF_LINES: "${CI_MAX_DIFF_LINES}"

jobs:
  review:
    name: ${ciCheckName(slug)}
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - name: Checkout base commit
        uses: ${pin(ACTION_PINS.checkout)}
        with:
          ref: \${{ github.event.pull_request.base.sha }}
          persist-credentials: false

      - name: Set up Node
        uses: ${pin(ACTION_PINS.setupNode)}
        with:
          node-version: "${NODE_VERSION}"

      - name: Run DevDigest review agent
        run: |
          if [ ! -f "${runner}" ]; then
            msg="DevDigest agent ${slug} is not on the base branch yet (this is its install PR); review skipped."
            echo "::notice::$msg"
            echo "$msg" >> "$GITHUB_STEP_SUMMARY"
            exit 0
          fi
          node ${runner}
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
          DEVDIGEST_AGENT_SLUG: ${slug}
          DEVDIGEST_POST_AS: ${input.postAs}

      - name: Upload result artifact
        if: always()
        uses: ${pin(ACTION_PINS.uploadArtifact)}
        with:
          name: devdigest-result-${slug}
          path: devdigest-result.json
          if-no-files-found: ignore
          retention-days: 30
`;
}

export interface WorkflowLintResult {
  parseError?: { line: number; message: string };
  warnings: { code: string; message: string }[];
}

const FULL_SHA_USES = /^[\w.-]+\/[\w./-]+@[0-9a-f]{40}(\s|$)/;
const EXPR = /\$\{\{[\s\S]*?\}\}/;

/** Parse + lint a (possibly user-edited) workflow. Parse errors map to the server 422. */
export function lintWorkflow(text: string): WorkflowLintResult {
  const doc = parseDocument(text);
  const err = doc.errors[0];
  if (err) {
    return {
      parseError: { line: err.linePos?.[0]?.line ?? 1, message: err.message },
      warnings: [],
    };
  }
  const warnings: WorkflowLintResult['warnings'] = [];
  const js = doc.toJS() as unknown;
  const wf = (js && typeof js === 'object' ? js : {}) as Record<string, unknown>;

  const on = wf.on ?? wf['true' as keyof typeof wf];
  const triggers =
    typeof on === 'string' ? [on] : Array.isArray(on) ? on : on && typeof on === 'object' ? Object.keys(on) : [];
  if (triggers.some((t) => t !== 'pull_request')) {
    warnings.push({
      code: 'unsafe_trigger',
      message: 'Workflow uses a trigger other than pull_request (e.g. pull_request_target runs with secrets on untrusted code).',
    });
  }

  const jobs = (wf.jobs && typeof wf.jobs === 'object' ? wf.jobs : {}) as Record<string, unknown>;
  for (const job of Object.values(jobs)) {
    const steps = (job as { steps?: unknown })?.steps;
    if (!Array.isArray(steps)) continue;
    for (const step of steps as Record<string, unknown>[]) {
      if (typeof step?.uses === 'string' && !step.uses.startsWith('./') && !FULL_SHA_USES.test(step.uses)) {
        warnings.push({
          code: 'unpinned_action',
          message: `Action "${step.uses}" is not pinned to a full commit SHA.`,
        });
      }
      if (typeof step?.run === 'string' && EXPR.test(step.run)) {
        warnings.push({
          code: 'expression_in_run',
          message: 'A run step contains a ${{ }} expression; pass values through env instead.',
        });
      }
    }
  }
  return { warnings };
}
